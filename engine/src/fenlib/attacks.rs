pub fn get_white_attacks(array: &Array) -> u64 {
    let all_pieces: u64 = array[WHITE] | array[BLACK];

    let mut attacks: u64 = king_attack(array[KING_W]);

    let mut pawns: u64 = array[PAWN_W];
    let mut knights: u64 = array[KNIGHT_W];
    let mut rooks: u64 = array[ROOK_W];
    let mut bishops: u64 = array[BISHOP_W];
    let mut queens: u64 = array[QUEEN_W];

    while pawns != 0 {
        let square: u32 = pawns.trailing_zeros();
        let piece: u64 = 1u64 << square;
        attacks |= white_pawn_attack(piece);
        pawns &= !piece;
    }

    while knights != 0 {
        let square: u32 = knights.trailing_zeros();
        let piece: u64 = 1u64 << square;
        attacks |= knight_attack(piece);
        knights &= !piece;
    }

    while rooks != 0 {
        let square: u32 = rooks.trailing_zeros();
        let piece: u64 = 1u64 << square;
        attacks |= rook_attack(piece, all_pieces);
        rooks &= !piece;
    }

    while bishops != 0 {
        let square: u32 = bishops.trailing_zeros();
        let piece: u64 = 1u64 << square;
        attacks |= bishop_attack(piece, all_pieces);
        bishops &= !piece;
    }

    while queens != 0 {
        let square: u32 = queens.trailing_zeros();
        let piece: u64 = 1u64 << square;
        attacks |= queen_attack(piece, all_pieces);
        queens &= !piece;
    }

    attacks
}

