pub fn bishop_attack(pos: u64, all: u64) -> u64 {
    let mut attacks: u64 = EMPTY;
    let index: usize = pos.leading_zeros() as usize;
    for dir in BISHOP_DIRS {
        let ray: u64 = RAY_OCC[dir][index];
        let blockers: u64 = ray & all;

        if blockers == 0 {
            attacks |= ray
        } else {
            attacks |= slider_attack(pos, blockers, dir)
        }
    }

    attacks
}

